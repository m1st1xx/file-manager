CREATE SCHEMA IF NOT EXISTS files;

-- Папка пользователя на диске (бывшее поле users.folder_path).
-- user_id — id аккаунта из auth-service; внешнего ключа между схемами
-- сервисов нет намеренно: каждый сервис владеет только своими данными.
CREATE TABLE IF NOT EXISTS files.storages (
    user_id INTEGER PRIMARY KEY,
    folder_path TEXT NOT NULL
);

-- Предметы пользователя (бывшая таблица subjects из new_users.db)
CREATE TABLE IF NOT EXISTS files.subjects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES files.storages(user_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    UNIQUE (user_id, name)
);

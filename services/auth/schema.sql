CREATE SCHEMA IF NOT EXISTS auth;

-- Аккаунты (бывшая таблица users из new_users.db)
CREATE TABLE IF NOT EXISTS auth.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Старые аккаунты (бывшая таблица users из users.db) для «входа старым способом».
-- migrated_user_id — аккаунт, созданный после выбора имени пользователя.
CREATE TABLE IF NOT EXISTS auth.legacy_users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    group_number TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    folder_path TEXT NOT NULL,
    migrated_user_id INTEGER REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS legacy_users_login_idx
    ON auth.legacy_users (first_name, last_name, group_number);

-- Предметы старых аккаунтов (бывшая таблица subjects из users.db).
-- Передаются в files-service при переносе аккаунта.
CREATE TABLE IF NOT EXISTS auth.legacy_subjects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_user_id INTEGER NOT NULL REFERENCES auth.legacy_users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    UNIQUE (legacy_user_id, name)
);
